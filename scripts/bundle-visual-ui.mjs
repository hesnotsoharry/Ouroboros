// One-off bundler: concatenates renderer visual UI source into a single markdown
// file at repo root for design review. COPIES files (read-only); originals untouched.
import fs from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const roots = [
  "src/renderer/components",
  "src/renderer/styles",
  "src/renderer/themes",
];

function walk(dir, acc) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, acc);
    else acc.push(p.split(path.sep).join("/"));
  }
}

const LEAN = process.argv.includes("--lean");

function isVisual(f) {
  if (/\.(test|spec)\.[tj]sx?$/.test(f)) return false; // tests are noise for design review
  if (LEAN) {
    // Design-language layer only: tokens, palettes, typography, styling decisions.
    // Excludes .tsx/.jsx implementation — that returns for implementation after mockups.
    if (/\.(css|scss)$/.test(f)) return true; // token system + global stylesheets
    if (/\.(styles|Styles)\.ts$/.test(f)) return true; // inline-style definition modules
    if (f.startsWith("src/renderer/themes/") && f.endsWith(".ts")) return true; // theme palettes
    return false;
  }
  if (/\.(tsx|jsx|css|scss)$/.test(f)) return true; // components + stylesheets
  if (/\.(styles|Styles)\.ts$/.test(f)) return true; // inline-style definition modules
  if (f.startsWith("src/renderer/themes/") && f.endsWith(".ts")) return true; // theme color defs
  return false;
}

const langByExt = {
  ".tsx": "tsx",
  ".jsx": "jsx",
  ".ts": "ts",
  ".css": "css",
  ".scss": "scss",
};

const all = [];
for (const r of roots) if (fs.existsSync(r)) walk(r, all);
const selected = all.filter(isVisual).sort();

const out = [];
out.push(LEAN ? "# Design Language Bundle" : "# Renderer Visual UI Bundle");
out.push("");
out.push(
  "> Read-only snapshot for design review. Generated by `scripts/bundle-visual-ui.mjs`.",
);
out.push(
  LEAN
    ? `> Scope (lean): token system + global CSS, theme palettes (\`themes/*.ts\`), and inline-style modules (\`*.styles.ts\`). Component \`.tsx\` logic excluded — that returns for implementation after mockups.`
    : `> Scope: components (\`.tsx/.jsx\`), stylesheets (\`.css/.scss\`), inline-style modules (\`*.styles.ts\`), and theme definitions. Tests excluded.`,
);
out.push(`> ${selected.length} files. Generated ${new Date().toISOString()}.`);
out.push("");
out.push("## Table of contents");
out.push("");
for (const f of selected) out.push(`- ${f}`);
out.push("");
out.push("---");
out.push("");

let totalBytes = 0;
for (const f of selected) {
  const content = fs.readFileSync(f, "utf8");
  totalBytes += Buffer.byteLength(content);
  const lang = langByExt[path.extname(f)] ?? "";
  out.push(`## ${f}`);
  out.push("");
  out.push("```" + lang);
  out.push(content.replace(/\n$/, ""));
  out.push("```");
  out.push("");
}

const target = path.join(repoRoot, LEAN ? "DESIGN-LANGUAGE-BUNDLE.md" : "VISUAL-UI-BUNDLE.md");
fs.writeFileSync(target, out.join("\n"), "utf8");
console.log(`Wrote ${target}`);
console.log(`Files: ${selected.length}, source bytes: ${totalBytes} (~${Math.round(totalBytes / 1024)} KB)`);
console.log(`Bundle size: ${Math.round(fs.statSync(target).size / 1024)} KB`);
